// Qwen-coder challenges: Bug Hunt, Why?, Predict, Build -> submit with self-confidence -> evaluate -> reveal (next step).
import { api, pollJob } from "../api.js";
import { emptyState, LEVEL_NAMES } from "../components.js";
import { $, captureDrafts, codeBlock, confidenceBadge, confirmDialog, esc, icon, md, meter, restoreDrafts, severityChip, statusChip, timeAgo, toast } from "../ui.js";

const KINDS = [
  { key: "bug_hunt", title: "Bug Hunt", i8: "bug", la: "bug", text: "A realistic snippet with deliberately planted bugs. Find them all - they stay secret until the reveal." },
  { key: "why", title: "Why?", i8: "question-mark", la: "question-circle", text: "Code with a deliberate design decision. Explain WHY, the trade-offs, and what-if it were different." },
  { key: "predict", title: "Predict", i8: "visible", la: "eye", text: "Trace tricky code and predict the exact output - logic and careful analysis." },
  { key: "build", title: "Build", i8: "hammer", la: "hammer", text: "Build something small. The AI analyses your code, then hides the bugs it finds for a second hunt." },
];
const LANGS = ["python", "javascript", "typescript", "java", "cpp", "c", "csharp", "go", "rust", "sql"];

export async function render(root, app) {
  let challenges = [];
  let openId = null;
  let timer = null;
  const level = (app.me.progression || {}).level || 1;

  root.innerHTML = `<div class="flex flex-col gap-6">
    <div><h1 class="flex items-center gap-2 text-2xl font-extrabold">${icon("puzzle", "puzzle-piece")}Challenges</h1>
      <p class="text-sm muted">Generated by the Qwen coder at your level (LVL ${level} · ${LEVEL_NAMES[level - 1]}). Rate how sure you are - calibration trains metacognition.</p></div>
    <div class="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">${KINDS.map((k) => `<div class="card flex flex-col gap-3">
        <div class="flex items-center gap-3">${icon(k.i8, k.la, "ico8-lg")}<h2 class="text-lg font-bold">${k.title}</h2></div>
        <p class="flex-1 text-sm muted">${k.text}</p>
        <input data-topic="${k.key}" class="input" maxlength="200" placeholder="Topic (optional) e.g. caching, recursion">
        <div class="flex gap-2"><select data-lang="${k.key}" class="input !w-auto flex-1">${LANGS.map((l) => `<option>${l}</option>`).join("")}</select>
          <button data-gen="${k.key}" class="btn btn-primary"><i class="la la-magic"></i>Generate</button></div></div>`).join("")}</div>
    <div id="ch-list" class="flex flex-col gap-4"></div></div>`;

  root.querySelectorAll("[data-gen]").forEach((b) => (b.onclick = async () => {
    const kind = b.dataset.gen;
    b.disabled = true;
    try {
      const res = await api("/api/challenges", { method: "POST", body: { kind, topic: root.querySelector(`[data-topic="${kind}"]`).value, language: root.querySelector(`[data-lang="${kind}"]`).value } });
      openId = res.challenge.id;
      toast("The Qwen coder is designing your challenge...", "info");
      await load();
    } catch (e) { if (e.code !== "AI_OFFLINE") toast(e.message, "error"); }
    finally { b.disabled = false; }
  }));

  function solution(c) {
    const s = c.solution;
    if (!s) return "";
    const parts = [];
    if (s.planted_bugs) parts.push(`<div class="label">Planted bugs</div>${s.planted_bugs.map((b) => `<div class="mb-2 rounded-xl border border-[color:var(--border)] p-3 text-sm">
        <div class="flex flex-wrap items-center gap-2">${severityChip(b.severity)}${b.found ? '<span class="chip chip-good"><i class="la la-bullseye"></i>you found it</span>' : '<span class="chip"><i class="la la-eye-slash"></i>missed</span>'}<b>${esc(b.title)}</b><span class="font-mono text-xs muted">${esc(b.location)}</span></div>
        <p class="mt-1 text-2">${esc(b.description)}</p>${b.fix ? `<div class="md mt-1">${md("**Fix:** " + b.fix)}</div>` : ""}</div>`).join("")}`);
    if (s.expected_output) parts.push(`<div class="label">Expected output</div>${codeBlock(s.expected_output, "output")}`);
    if (s.explanation) parts.push(`<div class="label">Explanation</div><div class="md">${md(s.explanation)}</div>`);
    if (s.model_answer) parts.push(`<div class="label">Model answer</div><div class="md">${md(s.model_answer)}</div>`);
    if ((s.rubric || []).length) parts.push(`<div class="label">Rubric</div><ul class="list-disc pl-5 text-sm">${s.rubric.map((r) => `<li>${esc(r)}</li>`).join("")}</ul>`);
    if ((s.hidden_edge_cases || []).length) parts.push(`<div class="label">Hidden edge cases</div><ul class="list-disc pl-5 text-sm">${s.hidden_edge_cases.map((r) => `<li>${esc(r)}</li>`).join("")}</ul>`);
    if (s.reference_solution) parts.push(`<div class="label">Reference solution</div>${codeBlock(s.reference_solution, c.language)}`);
    return `<div class="mt-4 rounded-xl border border-[color:var(--accent)]/40 p-4"><div class="section-title">${icon("unlock", "unlock")}Solution (revealed)</div><div class="mt-3 space-y-3">${parts.join("")}</div></div>`;
  }

  function evaluation(c) {
    const ev = c.evaluation;
    if (!ev) return "";
    const ai = ev.ai_detection;
    const sb = c.submission_bugs || {};
    return `<div class="mt-4 rounded-xl border border-[color:var(--border)] p-4">
        <div class="flex flex-wrap items-center justify-between gap-2"><div class="section-title">${icon("inspection", "clipboard-check")}Evaluation</div>${confidenceBadge(ev.meta)}</div>
        <div class="mt-3 grid gap-4 sm:grid-cols-[180px_1fr]">
          <div><div class="hero-figure">${Math.round(ev.score ?? 0)}<span class="text-lg muted">/100</span></div>
            ${ev.total_items ? `<div class="mt-1 text-xs muted">${(ev.found_items || []).length}/${ev.total_items} key items</div>` : ""}
            ${ev.self_confidence != null ? `<div class="mt-1 text-xs muted">You felt ${Math.round(ev.self_confidence)}% sure</div>` : ""}</div>
          <div><div class="md">${md(ev.feedback || "")}</div>
            ${(ev.hints || []).length ? `<div class="mt-2"><div class="label">What-if hints</div>${ev.hints.map((x) => `<div class="text-sm">- ${esc(x)}</div>`).join("")}</div>` : ""}</div></div>
        ${ai && ai.likelihood != null ? `<div class="mt-4"><div class="flex justify-between text-xs"><span class="text-2">AI-assistance estimate (fine - ownership matters)</span><span class="font-semibold">${Math.round(ai.likelihood * 100)}%</span></div>${meter(ai.likelihood * 100, { label: "AI-assistance" })}</div>` : ""}
        ${(ev.ownership_questions || []).length ? `<div class="mt-3"><div class="label">Ownership check - answer these in Chat</div>${ev.ownership_questions.map((q) => `<div class="text-sm">- ${esc(q)}</div>`).join("")}</div>` : ""}
        ${sb.hidden_count ? `<div class="mt-4 rounded-xl border border-[color:var(--accent-2)]/40 p-3 text-sm">${icon("lock", "lock", "!h-5 !w-5 inline")} <b>${sb.hidden_count} hidden bug(s) in your own code.</b> Hunt them (one per line):
            <textarea data-sguess="${c.id}" data-draft="sguess-${c.id}" class="input mt-2" rows="3"></textarea>
            <button class="btn btn-primary btn-sm mt-2" data-shunt="${c.id}"><i class="la la-search"></i>Check</button></div>` : ""}
        ${(sb.visible || []).length ? `<div class="mt-3 space-y-2">${sb.visible.map((b) => `<div class="rounded-xl border border-[color:var(--border)] p-3 text-sm"><div class="flex flex-wrap items-center gap-2">${severityChip(b.severity)}${statusChip(b.status)}<b>${esc(b.title)}</b></div><p class="mt-1 text-2">${esc(b.description)}</p>${b.fix ? `<div class="md">${md("**Fix:** " + b.fix)}</div>` : ""}</div>`).join("")}</div>` : ""}
      </div>`;
  }

  function detail(c) {
    const busy = ["generating", "evaluating"].includes(c.status);
    if (c.status === "generating") return '<p class="mt-3 text-sm muted"><i class="la la-cog la-spin"></i> The Qwen coder is generating this challenge...</p>';
    if (c.status === "failed") return `<p class="mt-3 text-sm text-[color:var(--critical)]"><i class="la la-exclamation-circle"></i> ${esc(c.error || "Generation failed.")}</p>`;
    return `<div class="mt-4 space-y-3">
        <div class="flex flex-wrap items-center gap-2">${confidenceBadge(c.generation)}${(c.skills || []).map((s) => `<span class="chip">${esc(s)}</span>`).join("")}${c.estimated_minutes ? `<span class="chip"><i class="la la-clock"></i>${Math.round(c.estimated_minutes)} min</span>` : ""}</div>
        <div class="md">${md(c.prompt)}</div>
        ${c.code ? codeBlock(c.code, c.language) : ""}
        ${c.question ? `<div class="rounded-xl bg-[color:var(--surface-2)] p-3"><div class="label">Question</div><div class="md">${md(c.question)}</div></div>` : ""}
        ${c.error ? `<p class="text-sm text-[color:var(--critical)]"><i class="la la-exclamation-circle"></i> ${esc(c.error)} - you can submit again.</p>` : ""}
        ${c.status === "open" ? `<label class="block"><span class="label">${c.kind === "build" ? "Your code" : "Your answer"}</span>
            <textarea data-answer="${c.id}" data-draft="answer-${c.id}" class="input ${c.kind === "build" ? "input-mono" : ""}" rows="${c.kind === "build" ? 12 : 6}" maxlength="30000">${esc(c.submission || "")}</textarea></label>
          <div class="flex flex-wrap items-center gap-3 text-sm"><label class="flex items-center gap-2">How sure are you? <input data-conf="${c.id}" data-draft="conf-${c.id}" type="range" min="0" max="100" value="50" class="w-32"><span data-conf-v="${c.id}">50%</span></label>
            <button class="btn btn-primary" data-submit="${c.id}"><i class="la la-paper-plane"></i>Submit for evaluation</button>
            <button class="btn btn-ghost btn-sm" data-giveup="${c.id}"><i class="la la-flag"></i>Give up & reveal</button></div>` : ""}
        ${busy ? '<p class="text-sm muted"><i class="la la-cog la-spin"></i> Evaluating with the secret answer key...</p>' : ""}
        ${c.submission && c.status !== "open" ? `<details><summary class="cursor-pointer text-sm font-semibold">Your submission</summary>${c.kind === "build" ? codeBlock(c.submission, c.language) : `<div class="md mt-2">${md(c.submission)}</div>`}</details>` : ""}
        ${evaluation(c)}
        ${c.status === "evaluated" ? `<button class="btn btn-soft" data-reveal="${c.id}"><i class="la la-unlock"></i>Reveal solution (next step)</button>` : ""}
        ${solution(c)}</div>`;
  }

  function card(c) {
    const kind = KINDS.find((k) => k.key === c.kind) || KINDS[0];
    const open = openId === c.id;
    return `<article class="card fade-in ${open ? "glow-border" : ""}" data-cid="${c.id}">
      <button class="flex w-full items-center gap-3 text-left" data-toggle="${c.id}">
        ${icon(kind.i8, kind.la)}<div class="min-w-0 flex-1"><div class="truncate font-bold">${esc(c.title)}</div>
        <div class="mt-0.5 flex flex-wrap items-center gap-1.5 text-xs"><span class="chip">${kind.title}</span><span class="chip">LVL ${c.level}</span><span class="chip">${esc(c.language)}</span>${statusChip(c.status)}
        ${c.score != null ? `<span class="chip chip-accent">${Math.round(c.score)}/100</span>` : ""}<span class="muted">${timeAgo(c.created_at)}</span></div></div>
        <i class="la ${open ? "la-angle-up" : "la-angle-down"} text-xl muted"></i></button>
      ${open ? detail(c) : ""}</article>`;
  }

  let lastHtml = "";
  async function load() {
    if (!root.isConnected) return;  // the user left this page: stop polling
    const data = await api("/api/challenges", { background: true });
    if (!root.isConnected) return;
    challenges = data.challenges;
    const list = $("#ch-list", root);
    const html = challenges.length ? challenges.map(card).join("")
      : emptyState(icon("puzzle", "puzzle-piece", "ico8-lg"), "No challenges yet", "Pick a challenge type above - the Qwen coder will tailor it to your level and weak spots.");
    if (html !== lastHtml) {  // unchanged: keep the DOM (focus, open sections, typing) instead of rebuilding it
      lastHtml = html;
      const drafts = captureDrafts(list);
      list.innerHTML = html;
      wire(list);
      restoreDrafts(list, drafts);
    }
    clearTimeout(timer);
    if (challenges.some((c) => ["generating", "evaluating"].includes(c.status))) timer = setTimeout(load, 2500);
  }

  function wire(list) {
    list.querySelectorAll("[data-toggle]").forEach((b) => (b.onclick = () => { openId = openId === b.dataset.toggle ? null : b.dataset.toggle; load(); }));
    list.querySelectorAll("[data-conf]").forEach((r) => (r.oninput = () => { list.querySelector(`[data-conf-v="${r.dataset.conf}"]`).textContent = `${r.value}%`; }));
    list.querySelectorAll("[data-submit]").forEach((b) => (b.onclick = async () => {
      const id = b.dataset.submit;
      const answer = list.querySelector(`[data-answer="${id}"]`).value;
      if (!answer.trim()) { toast("Write your answer first.", "warn"); return; }
      b.disabled = true;
      try {
        const res = await api(`/api/challenges/${id}/submit`, { method: "POST", body: { answer, confidence: Number(list.querySelector(`[data-conf="${id}"]`).value) } });
        await load();
        const job = await pollJob(res.job_id);
        if (job.status === "failed") toast(job.error || "Evaluation failed", "error", 7000);
        await load();
      } catch (e) { if (e.code !== "AI_OFFLINE") toast(e.message, "error"); b.disabled = false; }
    }));
    list.querySelectorAll("[data-giveup]").forEach((b) => (b.onclick = async () => {
      if (!(await confirmDialog("Give up?", "The solution will be revealed and this challenge scores 0 (no progress).", { okLabel: "Reveal" }))) return;
      try { await api(`/api/challenges/${b.dataset.giveup}/reveal`, { method: "POST", body: { give_up: true } }); await load(); } catch (e) { toast(e.message, "error"); }
    }));
    list.querySelectorAll("[data-reveal]").forEach((b) => (b.onclick = async () => {
      try { await api(`/api/challenges/${b.dataset.reveal}/reveal`, { method: "POST", body: { give_up: false } }); await load(); } catch (e) { toast(e.message, "error"); }
    }));
    list.querySelectorAll("[data-shunt]").forEach((b) => (b.onclick = async () => {
      const id = b.dataset.shunt;
      const guesses = list.querySelector(`[data-sguess="${id}"]`).value.split("\n").map((s) => s.trim()).filter(Boolean);
      if (!guesses.length) { toast("Write at least one hypothesis.", "warn"); return; }
      b.disabled = true;
      try {
        const res = await api(`/api/challenges/${id}/bughunt`, { method: "POST", body: { guesses } });
        const job = await pollJob(res.job_id);
        if (job.status === "succeeded") toast(`Found ${job.result.found.length} - ${job.result.remaining} still hidden.`, "success", 6000);
        else toast(job.error || "Check failed", "error");
        await load();
      } catch (e) { if (e.code !== "AI_OFFLINE") toast(e.message, "error"); b.disabled = false; }
    }));
  }

  await load();
  return () => clearTimeout(timer);
}
